function setFlag(key, value){
  if(!GAME.world) GAME.world = {flags:{}};
  if(!GAME.world.flags) GAME.world.flags = {};
  const previous = GAME.world.flags[key];
  GAME.world.flags[key] = value;
  Bus.emit("flag_set", {key, value, previous});
  if(typeof onContinuityFlagChanged === "function") onContinuityFlagChanged(key, value, previous);
  if(typeof syncCompanionsFromFlags === "function") syncCompanionsFromFlags();
}

function getFlag(key){
  return GAME.world.flags[key];
}
