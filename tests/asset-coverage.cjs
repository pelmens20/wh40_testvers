#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const inventory = JSON.parse(fs.readFileSync(path.join(root, 'tools/assets-inventory.json'), 'utf8'));
let registry = fs.readFileSync(path.join(root, 'js/content/assets.js'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const render = fs.readFileSync(path.join(root, 'js/ui/render.js'), 'utf8');
const panels = fs.readFileSync(path.join(root, 'js/ui/panels.js'), 'utf8');
const app = fs.readFileSync(path.join(root, 'js/app.js'), 'utf8');
const importer = fs.readFileSync(path.join(root, 'tools/import-user-assets.ps1'), 'utf8');
const availability = fs.readFileSync(path.join(root, 'js/content/assets-availability.js'), 'utf8');
assert.equal(inventory.expectedFileCount, 126, 'inventory should reflect all 126 user-listed assets');
assert.equal(inventory.files.length, 126, 'inventory entry count must equal expected count');
assert.equal(inventory.imageCount, 121, 'inventory image count');
assert.equal(inventory.audioCount, 5, 'inventory audio count');
assert.equal(new Set(inventory.files.map(x => x.path)).size, 126, 'inventory paths must be unique');
const expectedImagePaths = inventory.files.filter(x=>x.type==='image').map(x=>x.path);
const expectedAudioPaths = inventory.files.filter(x=>x.type==='audio').map(x=>x.path);
const mapped = new Set([...registry.matchAll(/(?:file|optionalFile)\s*:\s*["'](assets\/[^"']+)["']/g)].map(m=>m[1]));
for (const rel of expectedImagePaths) assert.ok(mapped.has(rel), `image path not connected to the asset registry: ${rel}`);
for (const rel of expectedAudioPaths) assert.ok(mapped.has(rel), `audio path not connected to the asset registry: ${rel}`);
assert.match(registry, /function getAsset\([\s\S]+?\[a\.file,\s*a\.optionalFile,\s*a\.fallbackFile\]/, 'getAsset must inspect optional file mapping');
assert.match(registry, /if\(cat === "audio"\) return/, 'audio should not be sent through image preloader');
assert.match(html, /js\/content\/asset-inventory\.js/);
assert.match(html, /js\/content\/assets-availability\.js/);
assert.match(panels, /function renderAssetArchive\(/, 'codex must expose full asset archive');
assert.match(panels, /data-asset-category=/, 'resource archive has category filtering');
assert.match(panels, /data-asset-search-form/, 'resource archive has search');
assert.match(panels, /<audio controls preload="none"/, 'audio is playable from resource archive');
assert.match(app, /data-asset-img/, 'asset cards recover gracefully when file is damaged/missing');
assert.match(app, /data-asset-search-form/, 'search/filter events are wired');
assert.match(importer, /D:\\game\\wh40_testvers\\assets/i, 'importer defaults to the user-provided asset folder');
assert.match(importer, /assets-availability\.js/, 'importer refreshes runtime availability map');
assert.match(render, /replace\(\/_\/g, "-"\)/, 'enemy IDs with underscores normalize to file keys');
assert.match(render, /"флак-броня":"flak-armor"/, 'armor key aliases use the actual art filename');
assert.match(render, /inquisition:"Inquisition"/, 'faction reputation IDs map to image registry IDs');
const available = new Set([...availability.matchAll(/["'](assets\/[A-Za-z0-9_./-]+)["']/g)].map(m=>m[1]));
const found = inventory.files.filter(x=>fs.existsSync(path.join(root,x.path))).length;
const inManifest = inventory.files.filter(x=>available.has(x.path)).length;
assert.ok(found >= 15, 'expected minimum bundled assets are present');
console.log(`PASS asset inventory: ${inventory.files.length} registered (${inventory.imageCount} images + ${inventory.audioCount} audio).`);
console.log(`PASS registry coverage: ${expectedImagePaths.length} image paths + ${expectedAudioPaths.length} audio paths connected.`);
console.log(`INFO packaged asset binaries: ${found}/126 expected files currently in this working copy; Windows importer resolves the remainder from D:\\game\\wh40_testvers\\assets.`);
console.log(`INFO current runtime availability manifest: ${inManifest}/126 expected files marked available.`);
