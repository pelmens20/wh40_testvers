function parseIntent(raw){
  const fixed = fixTypos(String(raw || "").trim());
  const text = fixed;
  const lower = text.toLowerCase();

  const intent = {
    raw: text,
    verb: null,
    method: null,
    tool: null,
    target: null,
    direction: null
  };

  for(const v of VERB_MAP){
    if(v.re.test(lower)){ intent.verb = v.verb; break; }
  }
  for(const m of METHOD_MAP){
    if(m.re.test(lower)){ intent.method = m.method; break; }
  }
  for(const t of TOOL_MAP){
    if(t.re.test(lower)){ intent.tool = t.tool; break; }
  }
  for(const t of TARGET_MAP){
    if(t.re.test(lower)){ intent.target = t.target; break; }
  }
  if(intent.verb === "move" || intent.verb === "approach" || intent.verb === "enter" || !intent.verb){
    for(const d of DIRECTION_MAP){
      if(d.re.test(lower)){ intent.direction = d.dir; if(!intent.verb) intent.verb = "move"; break; }
    }
    // Если игрок написал просто название локации — считаем перемещением
    if(!intent.direction && typeof LOCATIONS !== "undefined"){
      const cleaned = lower.replace(/^(иду|пойду|направляюсь|двигаюсь|шагаю|отправляюсь)\s*(в|к|на)?\s*/,"");
      for(const name of Object.keys(LOCATIONS)){
        const n = name.toLowerCase();
        if(lower.includes(n) || n.includes(cleaned) || cleaned.includes(n.split(" ")[0])){
          intent.direction = n;
          if(!intent.verb) intent.verb = "move";
          break;
        }
      }
    }
  }

  return intent;
}

/** Подсказки, если намерение не распознано */
function suggestActions(raw){
  const lower = String(raw || "").toLowerCase();
  const suggestions = [];
  if(/смотр|огляд|изуч|разгляд/.test(lower)) suggestions.push("осматриваюсь");
  if(/ид|пойд|направ|двига/.test(lower)) suggestions.push("иду в [место]");
  if(/говор|разгов|бесед|скаж/.test(lower)) suggestions.push("разговариваю с [NPC]");
  if(/взлом|хак|терминал|консол/.test(lower)) suggestions.push("взламываю терминал");
  if(/атак|стреля|бью|удар/.test(lower)) suggestions.push("атакую");
  if(/пряч|скры|тиш/.test(lower)) suggestions.push("тихо подхожу к [цели]");
  if(/леч|медик|аптеч/.test(lower)) suggestions.push("использую медикамент");
  if(suggestions.length === 0){
    suggestions.push("осматриваюсь", "иду в Архив", "разговариваю с сержантом", "/помощь");
  }
  return suggestions.slice(0, 4);
}
