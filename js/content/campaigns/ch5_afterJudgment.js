/* ============================================================
   CAMPAIGN / CH5 — «После Суда»
   ------------------------------------------------------------
   Эпилог кампании. Три ветки:
     - Служба (если игрок прошёл чисто)
     - Изгнание (если были сомнения)
     - Ветка принятия Сердца Варпа (источник голоса остаётся неопределённым)
   ============================================================ */

const CAMPAIGN_CH5 = {
  afterJudgment: {
    title: "Глава V — После Суда",
    startScene: "wh5_boot",
    scenes: {

      /* ---------- ВХОД ---------- */
      wh5_boot: {
        title: "ПОСЛЕ СУДА",
        text: (game) => {
          const c = game.character;
          const corr = c.corruption || 0;
          const flags = game.world.flags || {};

          // 1. Ветка принятия Сердца Варпа — не устанавливает источник голоса
          if (flags.acceptedWarpHeart) {
            const role = c.classId === "inquisitor" ? "инквизитор" : c.classId === "spaceMarine" ? "Астартес" : c.classId === "guardsman" ? "гвардеец" : "агент";
            return `Ты не помнишь, как вышел из штаб-квартиры. Помнишь только синий свет и голос. Он больше не шёпот — или тебе кажется, что он стал частью твоих мыслей.

Улей Хелдон-Прайм живёт своей жизнью. Люди снуют по делам, не зная, что под ними, в темноте, остался открытый вопрос, который ты связываешь с Сердцем Варпа.

Ты всё ещё ${role} по документам. Но внутри тебе кажется, что ты стал частью чужого плана. Это ощущение — не доказательство того, что голос прав. И план, каким бы он ни был, только начинается.`;
          }

          // 2. Служба — если игрок прошёл чисто (сотрудничал, Порча < 5)
          if (flags.ojCooperated && corr < 5) {
            return `Ты выходишь из штаб-квартиры. Улей встречает тебя привычным гулом.

Ты сделал то, что должен был. Закрыл Врата. Заплатил цену. Доложил правду.

Инквизиция не награждает. Но помнит. И, возможно, это важнее.

На столе — новое дело. Улей Лорес-Секундус. Подозрение на культ Тзинча.`;
          }

          // 3. Изгнание — если игрок оставил Врата или Порча 5–8
          if (flags.gateAbandoned) {
            return `Ты выходишь из штаб-квартиры. Улей встречает тебя привычным гулом. Но что-то не так.

Никто не смотрит на тебя. Никто не провожает. Инквизиция не наказала тебя — но и не оставила при себе.

Врата открыты. Ты ушёл. И это знание не уйдёт.

Ты — вольный агент. Без поддержки. Без надзора. Без прикрытия.`;
          }

          if (corr >= 9 && !flags.acceptedWarpHeart) {
            return `Ты выходишь из штаб-квартиры. Улей встречает тебя привычным гулом.

Инквизиция не казнила тебя. Пока. Но ты чувствуешь: они не отпустили. Не забудут. Не простят.

Ты заражён. Порча девять. Это — приговор, отложенный на неопределённый срок.

Ты — вольный агент. Без поддержки. Без надзора. Без прикрытия.`;
          }

          // 4. По умолчанию — изгнание
          return `Ты выходишь из штаб-квартиры. Улей встречает тебя привычным гулом.

Инквизиция не дала тебе нового дела. Но и не запретила.

Ты — вольный агент. Без поддержки. Без надзора. Без прикрытия.

Ты можешь идти куда хочешь. Делать что хочешь. Но каждый шаг — твой.`;
        },
        onEnter: () => {
          const c = GAME.character;
          const corr = c.corruption || 0;
          const flags = GAME.world.flags || {};
          setFlag("campaignComplete", false);

          if (flags.acceptedWarpHeart) {
            GAME._wh5Branch = "heart";
          } else if (flags.ojCooperated && corr < 5 && !flags.gateAbandoned) {
            GAME._wh5Branch = "service";
          } else {
            GAME._wh5Branch = "exile";
          }
        },
        choices: [
          { label: "Продолжить", goto: "wh5_branch" }
        ]
      },

      /* ---------- ВЕТКА ---------- */
      wh5_branch: {
        title: "ПУТЬ",
        text: (game) => {
          const branch = game._wh5Branch || "exile";
          if (branch === "service") {
            const c = game.character || {};
            const roleLine = c.classId === "inquisitor"
              ? "Ты — Инквизитор; следующее поручение остаётся в пределах твоих полномочий."
              : c.classId === "spaceMarine"
                ? "Ты — Астартес, прикомандированный к делу; дальнейшие действия потребуют согласования с командованием и соответствующими службами."
                : "Ты — гвардеец, которому поручили продолжить работу; дальнейшие приказы и снабжение зависят от командования.";
            return `Ты возвращаешься к работе. Инквизиция ждёт. Улей — ждёт. Последствия дела ещё не исчерпаны.

Твоё дело — не последнее. Таких дел будет много. ${roleLine}`;
          }
          if (branch === "heart") {
            return `Ты стоишь на краю улья. Смотришь вниз. Город живёт. Люди ходят. Тебе кажется, что ты уже не тот человек, которым был прежде; подтвердить эту перемену со стороны ты не можешь.

Ты слышишь голос, который связываешь с Тзинчем: «Иди. Твоё дело — не здесь. Ещё есть другие ульи. Другие Врата. Другие ключи». Его источник и намерения не подтверждены независимыми свидетельствами.`;
          }
          return `Ты не возвращаешься к работе. Инквизиция не дала тебе нового дела. Но и не запретила.

Ты — вольный агент. Без поддержки. Без надзора. Без прикрытия.

Ты можешь идти куда хочешь. Делать что хочешь. Но каждый шаг — твой.`;
        },
        choices: [
          { label: "Продолжить", goto: "wh5_branch_continue" }
        ]
      },

      wh5_branch_continue: {
        title: "ПЕРВЫЙ ШАГ",
        text: (game) => {
          const branch = game._wh5Branch || "exile";
          const flags = game.world.flags || {};
          let text = "";

          if (branch === "service") {
            text = `На столе — новое дело. Улей Лорес-Секундус, субсектор Гелдон. Подозрение на культ Тзинча. Ты берёшь папку.`;

            if (flags.lyraCompanion && !flags.lyraAngryAtYou) {
              text += `\n\nЛира ждёт у входа. Она смотрит на тебя так, будто видит впервые.`;
            }

            if (flags.hasServoSkull) {
              text += `\n\nСервочереп жужжит у плеча. Он уже передал данные Хесту.`;
            }

            const roleLine = game.character.classId === "inquisitor"
              ? "Ты — Инквизитор. Это твоя служба, со всеми её полномочиями и последствиями."
              : game.character.classId === "spaceMarine"
                ? "Ты — Астартес, направленный на задание; дальнейший путь зависит от приказов и оценки угрозы."
                : game.character.classId === "guardsman"
                  ? "Ты — солдат Астра Милитарум; дальнейший путь зависит от приказов, выживания и долга."
                  : "Твой дальнейший путь определяется твоим назначением и приказами.";
            text += `\n\n${roleLine}`;
          } else if (branch === "heart") {
            text = `Ты идёшь по улицам улья. Люди обходят тебя стороной. Не потому, что боятся. Потому, что чувствуют — ты другой.

Голос в голове говорит: «Ещё один улей. Ещё один ключ. Иди.»

Ты идёшь.`;

            if (flags.lyraCompanion && !flags.lyraAngryAtYou) {
              text += `\n\nЛира идёт за тобой. Она не знает, куда. Но она идёт.`;
            }

            if (flags.lyraAngryAtYou) {
              text += `\n\nЛиры нет. Она ушла. Ты не знаешь куда. Может быть — навсегда.`;
            }
          } else {
            text = `Ты стоишь у входа в улей. За тобой — штаб-квартира. Впереди — вся галактика.

Ты можешь идти куда угодно. Делать что угодно. Но каждый шаг — твой.`;

            if (flags.lyraCompanion && !flags.lyraAngryAtYou) {
              text += `\n\nЛира стоит рядом. Она не спрашивает, куда мы идём. Она просто идёт.`;
            }

            if (flags.lyraAngryAtYou) {
              text += `\n\nЛиры нет. Она осталась в улье. Или ушла. Ты не знаешь.`;
            }

            if (flags.hasServoSkull) {
              text += `\n\nСервочереп летит следом. Он не задаёт вопросов.`;
            }
          }

          return text;
        },
        choices: [
          {
            label: "Поговорить с Лирой",
            goto: "wh5_lyra",
            requires: { flag: { lyraCompanion: true } },
            requiresFailText: "Лиры рядом нет."
          },
          {
            label: "Расстаться с Лирой",     // ← НОВОЕ
            goto: "wh5_lyra_departure",
            requires: { flag: { lyraAngryAtYou: true } },
            requiresFailText: "Лиры нет или она не уходит."
          },
          {
            label: "Проверить сервочереп",
            goto: "wh5_servoskull",
            requires: { flag: { hasServoSkull: true } },
            requiresFailText: "Сервочерепа нет."
          },
          {
            label: "Идти вперёд",
            goto: "wh5_final"
          }
        ]
      },

      wh5_lyra_departure: {
        title: "ЛИРА УХОДИТ",
        text: `Лира стоит у входа. Она не смотрит на тебя.

— Я всё думала, — говорит она тихо. — О том, что было внизу. О телах. О том, что ты ушёл и оставил меня там.

Она поворачивается. В глазах — не злость. Что-то хуже. Пустота.

— Я не могу идти с тобой дальше. Не потому, что ты плохой. Потому, что я больше не верю.

Она уходит. Не оборачивается.`,
        effects: {
          flag: {
            lyraLeaves: true,
            lyraAngryAtYou: true
          }
        },
        choices: [
          { label: "Смотреть, как она уходит", goto: "wh5_final" },
          { label: "Попытаться остановить",      goto: "wh5_lyra_try_stop" }
        ]
      },

      wh5_lyra_try_stop: {
        title: "ПОПЫТКА ОСТАНОВИТЬ",
        text: `Ты окликаешь её. Она останавливается. Не оборачивается.

— Зачем? — спрашивает она. — Что ты хочешь сказать? Что ты не хотел? Что это была ошибка?

Она качает головой.

— Я видела смерть. Я видела, как ты уходишь. Я видела, что ты выбираешь. И я знаю теперь, кто ты.`,
        choices: [
          { label: "«Прости»",       goto: "wh5_lyra_forgive" },
          { label: "«Ты права. Иди»", goto: "wh5_final" }
        ]
      },

      wh5_lyra_forgive: {
        title: "ПРОЩЕНИЕ",
        text: `Ты говоришь это. Просто. Без оправданий.

Лира долго молчит. Потом кивает.

— Я не прощаю. Но я слышу.

Она уходит. На этот раз — окончательно.`,
        effects: {
          flag: {
            lyraLeaves: true,
            lyraForgiven: true
          }
        },
        choices: [
          { label: "Идти вперёд", goto: "wh5_final" }
        ]
      },
      /* ---------- РАЗГОВОР С ЛИРОЙ ---------- */
      wh5_lyra: {
        title: "ЛИРА",
        text: `Лира стоит у входа. Она выглядит уставшей. Но живой.

— Ты вернулся, — говорит она. — Или нет? Я не понимаю, что это было. Инквизиция. Суд. Врата.

Она смотрит на тебя внимательно.

— Что теперь?`,
        choices: [
          { label: "«Мы идём дальше»",  goto: "wh5_lyra_stay" },
          { label: "«Ты свободна»",     goto: "wh5_lyra_leave" }
        ]
      },

      wh5_lyra_stay: {
        title: "ВМЕСТЕ",
        text: `Лира кивает. Без улыбки. Но что-то в её взгляде меняется.

— Хорошо. Тогда — дальше. Куда бы ты ни шёл.`,
        effects: { flag: { lyraStaysFinal: true } },
        choices: [
          { label: "Идти вперёд", goto: "wh5_final" }
        ]
      },

      wh5_lyra_leave: {
        title: "СВОБОДА",
        text: `Лира долго смотрит на тебя. Потом кивает.

— Спасибо, — говорит она. — За то, что не соврал.

Она уходит. Ты смотришь ей вслед.`,
        effects: { flag: { lyraLeaves: true } },
        choices: [
          { label: "Идти вперёд", goto: "wh5_final" }
        ]
      },

      /* ---------- СЕРВОЧЕРЕП ---------- */
      wh5_servoskull: {
        title: "СЕРВОЧЕРЕП",
        text: (game) => {
          const flags = game.world.flags || {};
          if (flags.servoQuestComplete) {
            return `Сервочереп жужжит у плеча. Голос его — тихий, механический.

— Данные переданы Магосу Хесту. Он ждёт отчёта. Он не сказал, что делать с тобой.

Череп замолкает. Потом добавляет:

— Я останусь. Пока. Хозяин не приказал уходить.`;
          }
          return `Сервочереп жужжит у плеча. Голос его — тихий, механический.

— Данные переданы. Хозяин доволен. Он не сказал, что делать с тобой.

Череп замолкает. Потом добавляет:

— Я останусь. Пока.`;
        },
        choices: [
          { label: "Идти вперёд", goto: "wh5_final" }
        ]
      },

      /* ---------- ФИНАЛ ---------- */
      wh5_final: {
        title: "ЗАВЕРШЕНИЕ ПЕРВОЙ АРКИ",
        text: (game) => {
          const branch = game._wh5Branch || "exile";
          const flags = game.world.flags || {};

          let text = "";

          if (branch === "service") {
            const c = game.character || {};
            const roleLine = c.classId === "inquisitor"
              ? "Ты — Инквизитор. Ты участвовал в закрытии Врат и теперь отвечаешь за последствия решения."
              : c.classId === "spaceMarine"
                ? "Ты — Астартес. Ты выполнил свою часть операции; дальнейшие задачи требуют нового приказа и оценки угрозы."
                : c.classId === "guardsman"
                  ? "Ты — гвардеец. Ты выжил, выполнил полученные приказы и знаешь, что последствия не заканчиваются вместе с боем."
                  : "Ты выполнил порученную часть операции; дальнейшие задачи требуют нового назначения.";
            text = `Эта сюжетная арка завершена.

${roleLine}

Новое дело ждёт в другом улье. Подозрение на культ требует проверки; его наличие и масштаб ещё предстоит установить.`;
          } else if (branch === "heart") {
            const c = game.character || {};
            const roleLine = c.classId === "inquisitor"
              ? "Ты по-прежнему числишься Инквизитором, хотя собственное восприятие искажено пережитым."
              : c.classId === "spaceMarine"
                ? "Ты всё ещё Астартес, но сомнения в собственном восприятии могут осложнить выполнение приказов."
                : "Ты всё ещё солдат Империума, хотя пережитое оставило след, который нельзя оценить одним отчётом.";
            text = `Эта сюжетная арка завершена.

${roleLine}

Голос, который ты связываешь с Тзинчем, подталкивает тебя вперёд. Но ощущение героя не является независимым доказательством истинности голоса или его намерений.`;
          } else {
            const c = game.character || {};
            const roleLine = c.classId === "inquisitor"
              ? "Ты — отстранённый от прежней цепочки командования Инквизитор или агент под подозрением; твой статус требует подтверждения."
              : c.classId === "spaceMarine"
                ? "Твоё назначение в операции завершено, и теперь требуется выяснить, какие приказы остаются в силе."
                : "Ты остался без прежнего прикрытия и должен выяснить, какие приказы и обязательства ещё действуют.";
            text = `Эта сюжетная арка завершена.

${roleLine}

Ты свободен в выборе следующего шага, но последствия решений остаются с тобой.`;
          }

          if (flags.campaignComplete) {
            text += `\n\nКампания завершена полностью.`;
          }

          return text;
        },
        effects: {
          flag: { campaignComplete: false, chapter5Ending: true },
          xp: 120
        },
        choices: [
          { label: "Продолжить — Новый улей",  goto: "__chapter6__" },
          { label: "Начать новую кампанию",     goto: "__restart__" }
        ]
      }

    }
  }
};
