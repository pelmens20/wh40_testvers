/* ---------- Исправление частых опечаток ---------- */
const TYPO_FIXES = [
  { re:/пасматр|пасматрел|пасматрю|асматрел|осматрел|осматрюсь|асматриваю/gi, to:"осматриваю" },
  { re:/аткрыва|аткрыть|открть|открою/gi, to:"открываю" },
  { re:/гаварю|гаварить|скажю/gi, to:"говорю" },
  { re:/спраси|спроси|спрошю/gi, to:"спрашиваю" },
  { re:/ити|итти|пойти|пошол|пошёл/gi, to:"иду" },
  { re:/пайду|паиду/gi, to:"пойду" },
  { re:/аттакую/gi, to:"атакую" },
  { re:/убигаю|сбегаю/gi, to:"убегаю" },
  { re:/взлам|взломлю|хакаю/gi, to:"взламываю" },
  { re:/лечу|полечу|залечу/gi, to:"лечу" },
  { re:/чиню|починю/gi, to:"ремонтирую" },
  { re:/паищу|ишщу/gi, to:"ищу" },
  { re:/спрячусь|скрытсь/gi, to:"прячусь" }
];

function fixTypos(text){
  let out = text;
  for(const f of TYPO_FIXES) out = out.replace(f.re, f.to);
  return out;
}

