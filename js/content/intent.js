/* ============================================================
   SYSTEMS / INTENT.JS — парсер намерений игрока
   ------------------------------------------------------------
   Превращает свободный текст в структурированное действие:
     { verb, target, method, tool, modifier }
   Работает без AI — на регекспах и словарях.
   ============================================================ */

/* ---------- Словари ---------- */

/* Глаголы намерения → внутреннее действие */
